/// The domains common where the user is, from the device's preferred
/// locales, in order.
List<String> regionalMailDomains(List<Locale> locales) => [
  for (final l in locales)
    ...?kCountryMailDomains[(l.countryCode?.isNotEmpty ?? false) ? l.countryCode : _languageCountry[l.languageCode]],
];
